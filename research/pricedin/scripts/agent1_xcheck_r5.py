#!/usr/bin/env python3
"""R5 相互チェック（agent1 → agent2 の LITE・COHR・AAOI）: 出口PER法を共通の前提で再計算し、日本3社と並べる。
共通前提: N=5年、株主資本コスト 10%、出口PER 20倍・25倍、基準純利益 = 会社の今期予想（米国はガイダンス EPS 中央値×4×希薄化後株数）。
時価総額・基準純利益は各カード（stocks/<t>.md D）の値 [一次/計算]。共通前提は [推測]。
"""
N, KE = 5, 0.10
ROWS = [
    # 銘柄, 時価総額, 基準純利益, 基準の説明, 各担当の元の前提
    ("LITE", 1085.42 * 101.0, 4.20 * 4 * 101.0, "Q1 FY27 ガイド EPS $4.20×4", "ke 10%・出口 25倍・基準 FY28 コンセンサス"),
    ("COHR", 337.04 * 202.2, 1.95 * 4 * 202.2, "Q1 FY27 ガイド EPS $1.95×4", "ke 10%・出口 25倍・基準 FY28 コンセンサス"),
    ("AAOI", 115.59 * 92.8, 0.185 * 4 * 92.8, "Q3 2026 ガイド EPS $0.185×4", "ke 12%・出口 20倍・基準 2027 コンセンサス"),
    ("5803", 5598 * 16.557, 3260, "FY27 会社予想（08-07）", "ke 9%・出口 20倍・基準 FY27 会社予想"),
    ("6834", 6850 * 0.44696, 92, "FY27 会社予想（08-10）", "ke 9%・出口 20倍・基準 FY27 会社予想"),
    ("5802", 2452 * 31.1968, 3400, "FY27 会社予想（07-31）", "ke 8%・出口 15倍・基準 FY27 会社予想"),
]
print("| 銘柄 | 時価総額 | 基準純利益（説明）| 今期ベース PER | 必要な5年後純利益（20倍 / 25倍）| 必要な純利益 CAGR（20倍 / 25倍）| 元の前提 |")
print("|---|---|---|---|---|---|---|")
for t, mc, ni0, lab, orig in ROWS:
    req = {pe: mc * (1 + KE) ** N / pe for pe in (20, 25)}
    cg = {pe: (req[pe] / ni0) ** (1 / N) - 1 for pe in req}
    print(f"| {t} | {mc:,.0f} | {ni0:,.0f}（{lab}）| {mc/ni0:.1f}倍 | {req[20]:,.0f} / {req[25]:,.0f} | {cg[20]:+.1%} / {cg[25]:+.1%} | {orig} |")
