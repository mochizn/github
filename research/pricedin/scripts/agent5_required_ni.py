"""agent5: 8社を同じ物差しで比べる簡易逆算（R3）。
「今の時価総額を、4年後の純利益 × 出口PER で正当化する（割引率 r で4年割引）」ときに必要な4年後の純利益を、
足元の年率純利益（会社予想・ガイダンス年率）と比べる。DCF ではなく、銘柄間の比較のための共通の物差し。
入力は stocks/<ticker>.md の B・D の値（出典は各カード）。通貨は現地通貨（億円 / 百万ドル）。
"""
import itertools

# name: (時価総額, 足元の年率純利益, 足元の出所)
D = {
    "5803 フジクラ":  (92_700, 3_260, "FY27 会社予想（8/7）"),
    "6834 精工技研":  (3_062, 92, "FY27 会社予想（8/10）"),
    "5802 住友電工":  (76_500, 3_400, "FY27 会社予想（7/31）"),
    "LITE":          (109_600, 101 * 4.20 * 4, "Q1 FY27 ガイド EPS 中央値 $4.20×4 × 希薄化後1.01億株"),
    "COHR":          (202.2 * 337.04, 202.2 * 1.95 * 4, "Q1 FY27 ガイド EPS 中央値 $1.95×4 × 2.022億株"),
    "AAOI":          (92.8 * 115.59, 92.8 * 0.185 * 4, "Q3 2026 ガイド EPS 中央値 $0.185×4 × 9,280万株"),
    "GLW":           (141_900, 2_720, "Q2'26 コア純利益 $680M×4"),
    "FN":            (36.3 * 463.69, 36.3 * 4.175 * 4, "Q1 FY27 ガイド EPS 中央値 $4.175×4 × 3,630万株"),
}

def required(mcap, pe, r, years=4):
    return mcap * (1 + r) ** years / pe

print("| 銘柄 | 時価総額 | 足元の年率純利益 | 足元PER | 必要な4年後純利益（PER20・10%） | 倍率 | 必要な純利益 CAGR | 感応度: PER15・12% / PER25・8% の CAGR |")
print("|---|---|---|---|---|---|---|---|")
for k, (m, ni, src) in D.items():
    req = required(m, 20, 0.10)
    x = req / ni
    lo = (required(m, 25, 0.08) / ni) ** 0.25 - 1
    hi = (required(m, 15, 0.12) / ni) ** 0.25 - 1
    print(f"| {k} | {m:,.0f} | {ni:,.0f}（{src}） | {m/ni:.0f}倍 | {req:,.0f} | ×{x:.1f} | {x**0.25-1:+.0%} | {hi:+.0%} / {lo:+.0%} |")

# SOTP: 光以外に平時の PER を当てたときの光部分の PER
print()
print("| 銘柄 | 光の利益比率 | 光以外の PER | 光部分に残る時価総額 | 光部分の PER |")
print("|---|---|---|---|---|")
for name, mcap, ni, share in [("5803 フジクラ", 92_700, 3_260, 0.81), ("5802 住友電工", 76_500, 3_400, 0.28)]:
    for pe in (12, 15):
        opt = mcap - ni * (1 - share) * pe
        print(f"| {name} | {share:.0%} | {pe}倍 | {opt:,.0f} | {opt/(ni*share):.0f}倍 |")
