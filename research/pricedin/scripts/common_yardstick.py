#!/usr/bin/env python3
"""8社を同じ前提で並べ直す（agent3, R5 相互チェック）。

各カードの逆算は前提がばらばら（株主資本コスト: 日本 8〜9%・米国 9〜12%、出口PER の中心: 住友電工 15倍・
日本2社 20倍・米国 20〜25倍、期間: agent5 は4年・各カードは5年）。ここでは全銘柄に同じ前提を当てる。
  必要な N 年後純利益 = 時価総額 × (1+ke)^N ÷ 出口PER、CAGR = (必要純利益 ÷ 足元純利益)^(1/N) − 1
入力（時価総額・足元純利益）は scripts/agent5_required_ni.py と同じ値（出典は各 stocks/ カード）。GLW のみ 2026年コンセンサスも併記。
使い方: python3 scripts/common_yardstick.py → data/common_yardstick.md
"""
import os

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "data", "common_yardstick.md")
# 銘柄: (時価総額, 足元の年率純利益, 足元の出所, 各カードの前提 (ke, 出口PER, N), カードの必要CAGR)
ROWS = [
    ("5803 フジクラ", 92700, 3260, "FY27 会社予想", (0.09, 20, 5), "+17%"),
    ("6834 精工技研", 3062, 92, "FY27 会社予想", (0.09, 20, 5), "+21%"),
    ("5802 住友電工", 76500, 3400, "FY27 会社予想", (0.08, 15, 5), "+17%"),
    ("LITE", 109600, 1697, "Q1 FY27 ガイド年率", (0.10, 25, 5), "agent2 カード参照"),
    ("COHR", 68149, 1577, "Q1 FY27 ガイド年率", (0.10, 25, 5), "agent2 カード参照"),
    ("AAOI", 10727, 69, "Q3'26 ガイド年率", (0.12, 20, 5), "agent2 カード参照"),
    ("GLW", 141900, 2720, "Q2'26 コア年率", (0.09, 25, 5), "+25%（2026年コンセンサス基準）"),
    ("GLW（2026年コンセンサス基準）", 141926, 2835, "2026年コンセンサス EPS $3.28", (0.09, 25, 5), "+25%"),
    ("FN", 16832, 606, "Q1 FY27 ガイド年率", (0.10, 20, 5), "+15.5%（FY27 コンセンサス基準）"),
]
CASES = [(0.09, 20), (0.10, 20), (0.09, 25), (0.10, 15)]
N = 5


def cagr(mcap, ni0, ke, pe, n=N):
    return (mcap * (1 + ke) ** n / pe / ni0) ** (1 / n) - 1


L = ["# 共通の物差しでの再計算（agent3, R5 相互チェック）", "",
     "再現: `python3 scripts/common_yardstick.py`。全銘柄に同じ前提（期間 5年、株主資本コスト ke、出口PER）を当て、足元の純利益から必要な純利益 CAGR を出す [推測: 計算]。",
     "通貨は現地通貨（億円 / 百万ドル）。足元純利益の選び方（会社予想 / ガイド年率 / コンセンサス）は agent5 の共通表と同じ。", "",
     "| 銘柄 | 足元純利益（出所） | 足元PER | " + " | ".join(f"ke {k:.0%}・PER {p}" for k, p in CASES) + " | カード自身の前提 (ke・PER) | その前提での CAGR | カードの記載 |",
     "|---|---|---|" + "---|" * len(CASES) + "---|---|---|"]
for name, mcap, ni0, src, (ke, pe, n), card in ROWS:
    cells = [f"{cagr(mcap, ni0, k, p):+.1%}" for k, p in CASES]
    L.append(f"| {name} | {ni0:,}（{src}） | {mcap/ni0:.0f}倍 | " + " | ".join(cells) +
             f" | {ke:.0%}・{pe}倍 | {cagr(mcap, ni0, ke, pe, n):+.1%} | {card} |")
base = {r[0]: cagr(r[1], r[2], 0.09, 20) for r in ROWS}
jp = [base[k] for k in ("5803 フジクラ", "6834 精工技研", "5802 住友電工")]
L += ["", "## 読み", "",
      f"- 共通前提（ke 9%・PER 20倍・5年）での日本3社の必要 CAGR は {min(jp):+.0%}〜{max(jp):+.0%}。住友電工はカードの前提（ke 8%・PER 15倍）だと +17%、共通前提だと {base['5802 住友電工']:+.0%} と小さくなる → **住友電工の「要求が低い」は前提の差でさらに強まる**（逆ではない）。",
      "- ke を 9%→10% にしても CAGR は約 +1pt しか動かない。出口PER 20→25 倍の方が約 −4〜5pt と大きい → 銘柄間の比較で効くのは割引率より**出口PER の置き方**。カード間で出口PER の中心が 15〜25倍と違うので、比較は本表（または agent5 の表）の共通列で行うべき。",
      "- 日米の差（REPORT §5.2 #1）は前提をそろえても残る（共通前提で日本3社 +12〜21%、米国は FN（+16%）を除き +27〜64%。FN だけが日本株並み）。"]
open(OUT, "w").write("\n".join(L) + "\n")
